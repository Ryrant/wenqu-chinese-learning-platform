import { Hono, type Context } from "hono";
import * as readingVocabularyEndpoint from "../app/api/v1/reading/vocabulary/route";
import * as dialogueEndpoint from "../app/api/v1/dialogue/route";
import * as practiceEndpoint from "../app/api/v1/practice/route";
import * as journeysEndpoint from "../app/api/v1/journeys/route";
import * as vocabularyReviewEndpoint from "../app/api/v1/vocabulary-review/route";
import * as endpoint0 from "../app/api/v1/ability-profile/route";
import * as endpoint1 from "../app/api/v1/ai/generate/route";
import * as endpoint2 from "../app/api/v1/auth/change-password/route";
import * as endpoint3 from "../app/api/v1/auth/login/route";
import * as endpoint4 from "../app/api/v1/auth/logout/route";
import * as endpoint5 from "../app/api/v1/auth/session/route";
import * as endpoint6 from "../app/api/v1/auth/setup/route";
import * as endpoint7 from "../app/api/v1/content/upload/route";
import * as endpoint8 from "../app/api/v1/diagnostic-media/[id]/route";
import * as endpoint9 from "../app/api/v1/diagnostic-media/route";
import * as endpoint10 from "../app/api/v1/family-feedback/route";
import * as endpoint11 from "../app/api/v1/family-portfolio/route";
import * as endpoint13 from "../app/api/v1/health/route";
import * as endpoint14 from "../app/api/v1/knowledge/search/route";
import * as endpoint15 from "../app/api/v1/learning-sequences/[id]/report/route";
import * as endpoint16 from "../app/api/v1/settings/route";
import * as endpoint17 from "../app/api/v1/speech/submissions/route";
import * as endpoint18 from "../app/api/v1/student-cases/route";
import * as endpoint19 from "../app/api/v1/submissions/[id]/audio/route";
import * as endpoint20 from "../app/api/v1/submissions/route";
import * as endpoint21 from "../app/api/v1/teaching-followups/route";
import * as endpoint22 from "../app/api/v1/trial-batches/[id]/report/route";
import * as endpoint23 from "../app/api/v1/trial-batches/[id]/route";
import * as endpoint24 from "../app/api/v1/trial-batches/route";
import * as endpoint25 from "../app/api/v1/trial-records/report/route";
import * as endpoint26 from "../app/api/v1/workspace/actions/route";
import * as endpoint27 from "../app/api/v1/workspace/audits/route";
import * as endpoint28 from "../app/api/v1/workspace/route";

/** 浏览器和 Node/Workers 共用同一组标准 HTTP 处理器。 */
export function createApiApp(options: { remoteAddress?: (context: Context) => string | undefined } = {}) {
  const app = new Hono();
  app.get("/api/v1/vocabulary-review", (context) => vocabularyReviewEndpoint.GET(context.req.raw));
  app.post("/api/v1/vocabulary-review", (context) => vocabularyReviewEndpoint.POST(context.req.raw));
  app.all("/api/v1/vocabulary-review", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.get("/api/v1/practice", (context) => practiceEndpoint.GET(context.req.raw));
  app.post("/api/v1/practice", (context) => practiceEndpoint.POST(context.req.raw));
  app.all("/api/v1/practice", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.get("/api/v1/journeys", (context) => journeysEndpoint.GET(context.req.raw));
  app.post("/api/v1/journeys", (context) => journeysEndpoint.POST(context.req.raw));
  app.all("/api/v1/journeys", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.get("/api/v1/dialogue", (context) => dialogueEndpoint.GET(context.req.raw));
  app.post("/api/v1/dialogue", (context) => dialogueEndpoint.POST(context.req.raw));
  app.all("/api/v1/dialogue", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.get("/api/v1/reading/vocabulary", (context) => readingVocabularyEndpoint.GET(context.req.raw));
  app.post("/api/v1/reading/vocabulary", (context) => readingVocabularyEndpoint.POST(context.req.raw));
  app.all("/api/v1/reading/vocabulary", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.get("/api/v1/ability-profile", (context) => endpoint0.GET(context.req.raw));
  app.all("/api/v1/ability-profile", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.post("/api/v1/ai/generate", (context) => endpoint1.POST(context.req.raw));
  app.all("/api/v1/ai/generate", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.post("/api/v1/auth/change-password", (context) => endpoint2.POST(context.req.raw));
  app.all("/api/v1/auth/change-password", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.post("/api/v1/auth/login", (context) => endpoint3.POST(context.req.raw, options.remoteAddress?.(context)));
  app.all("/api/v1/auth/login", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.post("/api/v1/auth/logout", () => endpoint4.POST());
  app.all("/api/v1/auth/logout", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.get("/api/v1/auth/session", (context) => endpoint5.GET(context.req.raw));
  app.all("/api/v1/auth/session", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.post("/api/v1/auth/setup", (context) => endpoint6.POST(context.req.raw));
  app.all("/api/v1/auth/setup", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.post("/api/v1/content/upload", (context) => endpoint7.POST(context.req.raw));
  app.all("/api/v1/content/upload", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.get("/api/v1/diagnostic-media/:id", (context) => endpoint8.GET(context.req.raw, { params: Promise.resolve({ id: context.req.param("id") }) }));
  app.all("/api/v1/diagnostic-media/:id", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.post("/api/v1/diagnostic-media", (context) => endpoint9.POST(context.req.raw));
  app.all("/api/v1/diagnostic-media", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.get("/api/v1/family-feedback", (context) => endpoint10.GET(context.req.raw));
  app.post("/api/v1/family-feedback", (context) => endpoint10.POST(context.req.raw));
  app.all("/api/v1/family-feedback", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.get("/api/v1/family-portfolio", (context) => endpoint11.GET(context.req.raw));
  app.all("/api/v1/family-portfolio", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.get("/api/v1/health", () => endpoint13.GET());
  app.all("/api/v1/health", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.post("/api/v1/knowledge/search", (context) => endpoint14.POST(context.req.raw));
  app.all("/api/v1/knowledge/search", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.get("/api/v1/learning-sequences/:id/report", (context) => endpoint15.GET(context.req.raw, { params: Promise.resolve({ id: context.req.param("id") }) }));
  app.all("/api/v1/learning-sequences/:id/report", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.get("/api/v1/settings", (context) => endpoint16.GET(context.req.raw));
  app.post("/api/v1/settings", (context) => endpoint16.POST(context.req.raw));
  app.all("/api/v1/settings", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.post("/api/v1/speech/submissions", (context) => endpoint17.POST(context.req.raw));
  app.all("/api/v1/speech/submissions", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.get("/api/v1/student-cases", (context) => endpoint18.GET(context.req.raw));
  app.all("/api/v1/student-cases", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.get("/api/v1/submissions/:id/audio", (context) => endpoint19.GET(context.req.raw, { params: Promise.resolve({ id: context.req.param("id") }) }));
  app.all("/api/v1/submissions/:id/audio", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.post("/api/v1/submissions", (context) => endpoint20.POST(context.req.raw));
  app.all("/api/v1/submissions", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.get("/api/v1/teaching-followups", (context) => endpoint21.GET(context.req.raw));
  app.all("/api/v1/teaching-followups", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.get("/api/v1/trial-batches/:id/report", (context) => endpoint22.GET(context.req.raw, { params: Promise.resolve({ id: context.req.param("id") }) }));
  app.all("/api/v1/trial-batches/:id/report", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.get("/api/v1/trial-batches/:id", (context) => endpoint23.GET(context.req.raw, { params: Promise.resolve({ id: context.req.param("id") }) }));
  app.all("/api/v1/trial-batches/:id", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.get("/api/v1/trial-batches", (context) => endpoint24.GET(context.req.raw));
  app.post("/api/v1/trial-batches", (context) => endpoint24.POST(context.req.raw));
  app.all("/api/v1/trial-batches", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.get("/api/v1/trial-records/report", (context) => endpoint25.GET(context.req.raw));
  app.all("/api/v1/trial-records/report", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.post("/api/v1/workspace/actions", (context) => endpoint26.POST(context.req.raw));
  app.all("/api/v1/workspace/actions", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.get("/api/v1/workspace/audits", (context) => endpoint27.GET(context.req.raw));
  app.all("/api/v1/workspace/audits", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.get("/api/v1/workspace", (context) => endpoint28.GET(context.req.raw));
  app.all("/api/v1/workspace", (context) => context.json({ error: "method_not_allowed" }, 405));
  app.all("/api/*", (context) => context.json({ error: "not_found" }, 404));
  app.all("/api", (context) => context.json({ error: "not_found" }, 404));
  app.onError((error, context) => { console.error("API请求失败", error); return context.json({ error: "unexpected_error" }, 500); });
  return app;
}

export default createApiApp();
